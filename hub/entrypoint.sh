#!/usr/bin/env bash
# Hub pod entrypoint. HOME is the persistent volume, so herdr's saved
# machines, the SSH key, known_hosts and idle timers survive restarts.
#
# Then: run two supervised services, the idle bridge (hubctl idle-watch) and
# the web terminal (ttyd). The herdr TUI itself is not started here; each
# client starts its own:
#   attach   kubectl -n herdr-hub exec -it deploy/herdr-hub -- herdr
#   web      a browser tab on ttyd, which runs herdr per tab
# Herdr opens machine connections only while a TUI client is attached, so an
# unattended hub never keeps actors awake.
set -euo pipefail

# log and supervise, shared with the actor's entrypoint (common/service.sh).
# shellcheck disable=SC2034 # read by service.sh
LOG_TAG=herdr-hub RESTART_DELAY=5
for lib in /usr/local/lib/herdr-substrate/service.sh "$(dirname "$(readlink -f "$0")")/../common/service.sh"; do
  # shellcheck source=/dev/null
  [[ -f "${lib}" ]] && { . "${lib}"; break; }
done
declare -F supervise >/dev/null || { echo "[herdr-hub] service.sh not found" >&2; exit 1; }

: "${ATESPACE:?ATESPACE is not set}"
mkdir -p "${HOME}/.ssh" "${HOME}/.config/herdr"
chmod 0700 "${HOME}/.ssh"

# The hub's SSH key is generated here, on the volume, and never leaves the
# cluster. The setup script reads the public half (hubctl pubkey) into the
# ActorTemplate's AUTHORIZED_KEYS.
if [[ ! -f "${HOME}/.ssh/id_ed25519" ]]; then
  ssh-keygen -q -t ed25519 -N '' -C "herdr-hub" -f "${HOME}/.ssh/id_ed25519"
  log "generated hub SSH key $(ssh-keygen -lf "${HOME}/.ssh/id_ed25519.pub")"
fi

# Re-rendered on every start so config changes in the image take effect.
cat >"${HOME}/.ssh/config" <<EOF
# Generated by the hub entrypoint.
Host ate-*
    User root
    IdentityFile ${HOME}/.ssh/id_ed25519
    IdentitiesOnly yes
    # Actors cloned from one golden snapshot share its host key.
    HostKeyAlias herdr-substrate-${ATESPACE}
    UserKnownHostsFile ${HOME}/.ssh/known_hosts.herdr-substrate
    StrictHostKeyChecking accept-new
    ForwardAgent no
    ProxyCommand ate-wss-proxy %n
EOF
chmod 0600 "${HOME}/.ssh/config"

# herdr's config, seeded once (edit it on the volume afterwards). The hub's
# herdr must match the actors' (both pinned in the images), so release checks
# are off: upgrade by rebuilding both images together.
if [[ ! -f "${HOME}/.config/herdr/config.toml" ]]; then
  printf '[update]\nversion_check = false\n' >"${HOME}/.config/herdr/config.toml"
fi

for f in "${ATE_IDENTITY_BUNDLE:-/var/run/ate/identity/credential-bundle.pem}" \
         "${ATE_ROUTER_CA:-/var/run/ate/servicedns/trust-bundle.pem}" \
         "${ATE_API_TOKEN:-/var/run/ate/api-token/token}"; do
  [[ -s "${f}" ]] || log "WARNING: ${f} is missing; check the pod's projected volumes"
done

if [[ "${IDLE_WATCH:-true}" == "true" ]]; then
  supervise idle-watch hubctl idle-watch &
else
  log "idle bridge disabled (IDLE_WATCH=${IDLE_WATCH})"
fi

# --- herdr in the browser -----------------------------------------------------
# ttyd serves the herdr TUI as a web page; every browser tab is its own herdr
# client, exactly like every `attach`. It listens on loopback by default,
# reachable only through `kubectl port-forward` (the `web` command), so the
# same Kubernetes permissions guard it as guard `attach`. The production
# guides listen on the pod IP behind IAP or oauth2-proxy instead.
#   HUB_WEB              true | false (default true)
#   HUB_WEB_ADDR         listen address (default 127.0.0.1; 0.0.0.0 = all)
#   HUB_WEB_PORT         default 7681
#   HUB_WEB_AUTH_HEADER  optional; refuse requests without this header, which
#                        an authenticating proxy sets (e.g. X-Forwarded-Email)
#   HUB_WEB_INDEX        the page ttyd serves: its own plus hub/herdr-web.js,
#                        built into the image by hub/herdr-web-index
HUB_WEB="${HUB_WEB:-true}"
HUB_WEB_ADDR="${HUB_WEB_ADDR:-127.0.0.1}"
HUB_WEB_PORT="${HUB_WEB_PORT:-7681}"
if [[ "${HUB_WEB}" != "true" ]]; then
  log "web terminal disabled (HUB_WEB=${HUB_WEB})"
else
  # -W: tabs may type (ttyd is read-only otherwise); -O: refuse WebSockets
  # from other origins; the page title stays "herdr"; closing a tab only
  # detaches that client, so no "leave this page?" prompt. -I: the page with
  # herdr's copy (OSC 52), right-click menu and ctrl+v paste fixed.
  web_args=(-p "${HUB_WEB_PORT}" -W -O -w "${HOME}"
            -I "${HUB_WEB_INDEX:-/usr/local/share/herdr-hub/index.html}"
            -t titleFixed=herdr -t disableLeaveAlert=true)
  [[ "${HUB_WEB_ADDR}" == "0.0.0.0" ]] || web_args+=(-i "${HUB_WEB_ADDR}")
  [[ -z "${HUB_WEB_AUTH_HEADER:-}" ]] || web_args+=(-H "${HUB_WEB_AUTH_HEADER}")
  # A shared link must only ever be behind sign-in (README: Security notes).
  if [[ "${HUB_WEB_ADDR}" != 127.* && "${HUB_WEB_ADDR}" != localhost \
        && "${HUB_WEB_ADDR}" != ::1 && -z "${HUB_WEB_AUTH_HEADER:-}" ]]; then
    log "WARNING: the web terminal listens on ${HUB_WEB_ADDR} without HUB_WEB_AUTH_HEADER;" \
        "anyone who reaches that address gets a shell unless a sign-in proxy (IAP, oauth2-proxy) is the only way in"
  fi
  supervise web ttyd "${web_args[@]}" herdr &
  log "web terminal on ${HUB_WEB_ADDR}:${HUB_WEB_PORT}"
fi

log "ready (atespace ${ATESPACE}); attach with: herdr"
wait
